"""Demo run for visual inspection: N images per source and M mixed chains, with overlay sheets.

  python -m feature_bank.render_demo --out runs/renderer_demo_<date> [--per-source 50] [--chains 200]

Sources: library_single, intensity (PHP recipes), python_text, python_shapes, python_capri,
python_recipe (reviewed Python ladders). Chains: library-only chains of depth 1-3 plus Python
stages under / over library stages. Uses the corpus generator's own sampling, rendering and
acceptance, so what you see is what the corpus contains. Overlay sheets (12 rows each) are in
<out>/sheets/; per-image labels in <out>/manifest.jsonl.
"""
import argparse
import json
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import yaml

from feature_bank.bank02_smoke import ROOT

GROUPS = {
    "library_single": dict(mix={"library_single": 1.0}),
    "intensity_php": dict(mix={"intensity": 1.0}),
    "python_text": dict(mix={"python": 1.0}, python_sources={"python_text": 1.0}, python_chain_fraction=0.0),
    "python_shapes": dict(mix={"python": 1.0}, python_sources={"python_shapes": 1.0}, python_chain_fraction=0.0),
    "python_capri": dict(mix={"python": 1.0}, python_sources={"python_capri": 1.0}, python_chain_fraction=0.0),
    "python_recipe": dict(mix={"python": 1.0}, python_sources={"python_recipe": 1.0}),
    "chains_library": dict(mix={"chain": 1.0}),
    "chains_python": dict(mix={"python": 1.0}, python_sources={"python_text": 0.4, "python_shapes": 0.4, "python_capri": 0.2},
                          python_chain_fraction=1.0),
}


def job(args):
    from feature_bank.generate_corpus import make_image
    cfg, group, i, out = args
    d = Path(out) / "images" / group
    d.mkdir(parents=True, exist_ok=True)
    row, tries = make_image(cfg, f"demo-{group}", i, "seen", str(d))
    return group, row, tries


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--per-source", type=int, default=50)
    ap.add_argument("--chains", type=int, default=200)
    ap.add_argument("--config", default=str(ROOT / "configs/corpus_hybrid_v3.yaml"))
    a = ap.parse_args()
    out = Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=False)
    base = yaml.safe_load(Path(a.config).read_text(encoding="utf-8"))
    jobs = []
    for g, over in GROUPS.items():
        n = a.chains // 2 if g.startswith("chains") else a.per_source
        cfg = dict(base, **over)
        jobs += [(cfg, g, i, str(out)) for i in range(n)]
    rows = []
    with ProcessPoolExecutor(int(base["workers"])) as ex:
        for g, row, tries in ex.map(job, jobs):
            if row:
                row["demo_group"] = g
                rows.append(row)
    with (out / "manifest.jsonl").open("w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r) + "\n")
    from feature_bank.review import sheet
    (out / "sheets").mkdir()
    counts = {}
    for g in GROUPS:
        sel = [r for r in rows if r["demo_group"] == g]
        counts[g] = len(sel)
        for k in range(0, len(sel), 12):
            items = []
            for r in sel[k:k + 12]:
                stem = out / "images" / g / r["id"]
                lab = dict(heads=r["heads"], text=r["text"], clip=r["clip"], glyph_ids=r["glyph_ids"])
                items.append((stem, lab, f"[{r['chain_desc']}]" + (f" recipe={r['recipe']['name']} L{r['recipe']['level']}" if r.get("recipe") else "")))
            sheet(items, out / "sheets" / f"{g}_{k // 12:02d}.png")
    (out / "README.md").write_text(
        "# Renderer demo\n\nGenerated by `python -m feature_bank.render_demo`. Each sheet row: original | layer heads coloured "
        "(green = answer glyphs, grey = other text) | answer-glyph boxes; caption = present heads [level] and masked heads.\n\n"
        + "\n".join(f"- `{g}`: {n} images -> `sheets/{g}_*.png`" for g, n in counts.items()) + "\n", encoding="utf-8")
    print(json.dumps(counts))


if __name__ == "__main__":
    main()
